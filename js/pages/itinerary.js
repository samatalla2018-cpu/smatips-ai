function openActivityModal(container, dayId, activityId) {
  const activity = activityId ? store.get('activities', activityId) : null;
  openModal(activity ? 'تعديل النشاط' : 'إضافة نشاط', activityFormHtml(activity), () => {
    const form = qs('#activity-form');
    const placeSelect = qs('#activity-place-select');
    const mapsField = qs('#activity-mapsurl-field');

    if (placeSelect) {
      placeSelect.addEventListener('change', (e) => {
        const placeId = e.target.value;
        if (placeId) {
          const p = store.get('places', placeId);
          if (p) {
            form.querySelector('[name=title]').value = p.name;
            form.querySelector('[name=type]').value = p.type || 'other';
          }
          mapsField.hidden = true;
        } else {
          mapsField.hidden = false;
        }
      });
    }

    form.addEventListener('submit', (e) => {
      e.preventDefault();
      const fd = new FormData(form);
      const placeId = fd.get('placeId') || '';
      const mapsUrlRaw = placeId ? '' : fd.get('mapsUrl').trim();
      if (mapsUrlRaw && !isValidMapsUrl(mapsUrlRaw)) {
        toast('الرابط المُدخل ليس رابط Google Maps صالحًا', 'error');
        return;
      }
      const data = {
        title: fd.get('title').trim(),
        time: fd.get('time'),
        type: fd.get('type'),
        placeId: placeId || '',
        mapsUrl: mapsUrlRaw,
        cost: fd.get('cost'),
        notes: fd.get('notes').trim(),
      };
      if (!data.title) return;
      if (activity) {
        store.update('activities', activity.id, data);
        toast('تم تحديث النشاط', 'success');
      } else {
        const dayActivities = store.list('activities').filter((a) => a.dayId === dayId);
        const maxOrder = dayActivities.reduce((m, a) => Math.max(m, a.order ?? 0), -1);
        store.add('activities', { ...data, dayId, order: maxOrder + 1 });
        toast('تمت إضافة النشاط', 'success');
      }
      closeModal();
      renderItinerary(container);
    });
  });
}

function activityMapsInfo(a) {
  const trip = store.getTrip();
  if (a.placeId) {
    const p = store.get('places', a.placeId);
    if (p) return p.mapsUrl || mapsSearchUrl([p.name, p.city, p.country].filter(Boolean).join(' '));
  }
  if (a.mapsUrl) return a.mapsUrl;
  if (a.title) return mapsSearchUrl([a.title, trip.city, trip.country].filter(Boolean).join(' '));
  return null;
}

function moveActivity(dayId, activityId, direction) {
  const acts = store.list('activities').filter((a) => a.dayId === dayId).sort((a, b) => (a.order ?? 0) - (b.order ?? 0));
  const idx = acts.findIndex((a) => a.id === activityId);
  const swapIdx = direction === 'up' ? idx - 1 : idx + 1;
  if (idx === -1 || swapIdx < 0 || swapIdx >= acts.length) return;
  const a1 = acts[idx];
  const a2 = acts[swapIdx];
  const o1 = a1.order ?? idx;
  const o2 = a2.order ?? swapIdx;
  store.update('activities', a1.id, { order: o2 });
  store.update('activities', a2.id, { order: o1 });
}

