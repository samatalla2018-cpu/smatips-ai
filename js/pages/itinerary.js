function dayCardHtml(day, activities, allowReorder) {
  const isToday = day.date === todayStr();
  return `
    <div class="card mt-2" data-day-id="${day.id}">
      <div class="flex items-center justify-between">
        <div>
          <div class="flex items-center gap-2">
            <span class="font-bold">${formatDateAr(day.date)}</span>
            ${isToday ? '<span class="badge badge-success">اليوم</span>' : ''}
          </div>
          ${day.title ? `<div class="text-sm text-muted mt-1">${escapeHtml(day.title)}</div>` : ''}
        </div>
        <div class="item-actions">
          <button class="icon-btn btn-sm" style="width:32px;height:32px;" data-day-action="add-activity" aria-label="إضافة نشاط">${icon('plus', 15)}</button>
          <button class="icon-btn btn-sm" style="width:32px;height:32px;" data-day-action="edit" aria-label="تعديل اليوم">${icon('edit', 14)}</button>
          <button class="icon-btn btn-sm" style="width:32px;height:32px;" data-day-action="delete" aria-label="حذف اليوم">${icon('trash', 14)}</button>
        </div>
      </div>
      ${day.notes ? `<div class="text-sm text-muted mt-2">${escapeHtml(day.notes)}</div>` : ''}
      <div class="mt-3">
        ${activities.length ? activities.map((a, i) => activityItemHtml(a, i === 0, i === activities.length - 1, allowReorder)).join('') : `<div class="text-sm text-muted" style="text-align:center; padding:10px;">لا توجد أنشطة في هذا اليوم${itineraryPeriodFilter !== 'الكل' ? ' لهذه الفترة' : ''}</div>`}
      </div>
    </div>`;
}

function renderItinerary(container) {
  const trip = store.getTrip();
  autoGenerateDays(trip);

  const allDays = store.list('days').slice().sort((a, b) => (a.date > b.date ? 1 : -1));
  const allActivities = store.list('activities');
  const allowReorder = itineraryPeriodFilter === 'الكل';

  let days = allDays;
  if (itineraryPeriodFilter === 'اليوم الحالي') {
    days = allDays.filter((d) => d.date === todayStr());
  }

  const filters = `
    <div class="chip-row mt-2">
      <button class="chip ${itineraryPeriodFilter === 'الكل' ? 'active' : ''}" data-period="الكل">كل الأيام</button>
      <button class="chip ${itineraryPeriodFilter === 'اليوم الحالي' ? 'active' : ''}" data-period="اليوم الحالي">اليوم الحالي</button>
      <button class="chip ${itineraryPeriodFilter === 'صباح' ? 'active' : ''}" data-period="صباح">صباح</button>
      <button class="chip ${itineraryPeriodFilter === 'ظهر' ? 'active' : ''}" data-period="ظهر">ظهر</button>
      <button class="chip ${itineraryPeriodFilter === 'مساء' ? 'active' : ''}" data-period="مساء">مساء</button>
    </div>`;

  const daysHtml = days.map((day) => {
    let activities = allActivities.filter((a) => a.dayId === day.id).sort((a, b) => (a.order ?? 0) - (b.order ?? 0));
    if (['صباح', 'ظهر', 'مساء'].includes(itineraryPeriodFilter)) {
      activities = activities.filter((a) => activityPeriod(a.time) === itineraryPeriodFilter);
    }
    return dayCardHtml(day, activities, allowReorder);
  }).join('');

  container.innerHTML = `
    ${pageHeader({
      title: 'جدول الرحلة اليومي',
      desc: trip.startDate ? `من ${formatDateAr(trip.startDate)} إلى ${formatDateAr(trip.endDate) || '—'}` : 'خطط لكل يوم من رحلتك بالتفصيل',
      iconName: 'calendar',
      actions: `<button class="btn btn-primary btn-sm" id="add-day-btn">${icon('plus', 16)}<span>إضافة يوم</span></button>`,
    })}
    ${filters}
    <div id="days-list">
      ${days.length ? daysHtml : emptyState(
        allDays.length
          ? { iconName: 'calendar', title: 'لا يوجد يوم مطابق', desc: 'لا يوجد يوم بتاريخ اليوم ضمن الأيام المضافة.' }
          : { iconName: 'calendar', title: 'لا يوجد جدول بعد', desc: 'أضف تواريخ رحلتك في صفحة بيانات الرحلة لإنشاء الأيام تلقائيًا، أو أضف يومًا يدويًا.' }
      )}
    </div>
  `;

  qs('#add-day-btn').addEventListener('click', () => openDayModal(container));

  qsa('[data-period]').forEach((btn) => {
    btn.addEventListener('click', () => { itineraryPeriodFilter = btn.dataset.period; renderItinerary(container); });
  });

  qs('#days-list').addEventListener('click', (e) => {
    const dayEl = e.target.closest('[data-day-id]');
    if (!dayEl) return;
    const dayId = dayEl.dataset.dayId;

    const dayAction = e.target.closest('[data-day-action]')?.dataset.dayAction;
    if (dayAction === 'add-activity') {
      openActivityModal(container, dayId);
      return;
    }
    if (dayAction === 'edit') {
      openDayModal(container, dayId);
      return;
    }
    if (dayAction === 'delete') {
      if (confirm('سيؤدي هذا لحذف اليوم وكل أنشطته. هل تريد المتابعة؟')) {
        store.list('activities').filter((a) => a.dayId === dayId).forEach((a) => store.remove('activities', a.id));
        store.remove('days', dayId);
        toast('تم حذف اليوم');
        renderItinerary(container);
      }
      return;
    }

    const activityEl = e.target.closest('[data-activity-id]');
    if (!activityEl) return;
    const activityId = activityEl.dataset.activityId;
    const activityAction = e.target.closest('[data-activity-action]')?.dataset.activityAction;
    if (activityAction === 'edit') {
      openActivityModal(container, dayId, activityId);
    } else if (activityAction === 'delete') {
      if (confirm('هل تريد حذف هذا النشاط؟')) {
        store.remove('activities', activityId);
        toast('تم حذف النشاط');
        renderItinerary(container);
      }
    } else if (activityAction === 'move-up') {
      moveActivity(dayId, activityId, 'up');
      renderItinerary(container);
    } else if (activityAction === 'move-down') {
      moveActivity(dayId, activityId, 'down');
      renderItinerary(container);
    }
  });
}

registerRoute('/itinerary', renderItinerary);
