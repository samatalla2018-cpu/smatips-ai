// صفحة جدول الرحلة اليومي — أيام وأنشطة CRUD كامل + ربط بالأماكن المحفوظة + إعادة ترتيب + فلترة حقيقية

let itineraryPeriodFilter = 'الكل';

function todayStr() {
  const d = new Date();
  return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`;
}

function activityPeriod(time) {
  if (!time) return null;
  const hour = Number(time.split(':')[0]);
  if (hour < 12) return 'صباح';
  if (hour < 17) return 'ظهر';
  return 'مساء';
}

// إنشاء أيام الرحلة تلقائيًا حسب تواريخ الرحلة، مرة واحدة فقط إذا لم توجد أي أيام بعد
function autoGenerateDays(trip) {
  if (!trip.startDate || !trip.endDate) return false;
  if (store.list('days').length > 0) return false;
  const start = new Date(trip.startDate + 'T00:00:00');
  const end = new Date(trip.endDate + 'T00:00:00');
  if (isNaN(start.getTime()) || isNaN(end.getTime()) || end < start) return false;
  const diffDays = Math.round((end - start) / 86400000) + 1;
  if (diffDays > 60) return false;
  for (let d = new Date(start); d <= end; d.setDate(d.getDate() + 1)) {
    const dateStr = `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`;
    store.add('days', { date: dateStr, title: '', notes: '' });
  }
  return true;
}

// ---------- نموذج اليوم ----------
function dayFormHtml(day) {
  const d = day || {};
  const trip = store.getTrip();
  return `
    <form id="day-form" class="flex-col gap-3">
      <div class="field">
        <label>التاريخ</label>
        <input type="date" name="date" required value="${escapeHtml(d.date || trip.startDate || '')}" />
      </div>
      <div class="field">
        <label>عنوان اليوم (اختياري)</label>
        <input type="text" name="title" placeholder="مثال: يوم استكشاف وسط المدينة" value="${escapeHtml(d.title || '')}" />
      </div>
      <div class="field">
        <label>ملاحظات (اختياري)</label>
        <textarea name="notes" placeholder="أي تفاصيل عامة عن اليوم...">${escapeHtml(d.notes || '')}</textarea>
      </div>
      <div class="modal-actions">
        <button type="submit" class="btn btn-primary btn-block">${icon('check', 16)}<span>${day ? 'حفظ التعديلات' : 'إضافة اليوم'}</span></button>
      </div>
    </form>`;
}

function openDayModal(container, dayId) {
  const day = dayId ? store.get('days', dayId) : null;
  openModal(day ? 'تعديل اليوم' : 'إضافة يوم', dayFormHtml(day), () => {
    qs('#day-form').addEventListener('submit', (e) => {
      e.preventDefault();
      const fd = new FormData(e.target);
      const data = { date: fd.get('date'), title: fd.get('title').trim(), notes: fd.get('notes').trim() };
      if (!data.date) return;
      if (day) {
        store.update('days', day.id, data);
        toast('تم تحديث اليوم', 'success');
      } else {
        store.add('days', data);
        toast('تمت إضافة اليوم', 'success');
      }
      closeModal();
      renderItinerary(container);
    });
  });
}

